std::vector<std::byte> b(std::string_view sv)
{
    std::vector<std::byte> v;
    v.reserve(sv.size());
    for (char c : sv)
        v.push_back(static_cast<std::byte>(c));
    return v;
}

std::vector<std::byte> b_hex(std::string_view hex)
{
    auto nibble = [](char c) -> unsigned
    {
        if (c >= '0' && c <= '9')
            return static_cast<unsigned>(c - '0');
        if (c >= 'a' && c <= 'f')
            return static_cast<unsigned>(c - 'a' + 10);
        if (c >= 'A' && c <= 'F')
            return static_cast<unsigned>(c - 'A' + 10);
        return 0;
    };

    std::vector<std::byte> v;
    v.reserve(hex.size() / 2);
    for (std::size_t i = 0; i + 1 < hex.size(); i += 2)
        v.push_back(static_cast<std::byte>((nibble(hex[i]) << 4) | nibble(hex[i + 1])));
    return v;
}

struct xorshift_random
{
    explicit xorshift_random(std::uint64_t seed) : state(seed) {}

    std::uint64_t next()
    {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        return state;
    }

private:
    std::uint64_t state;
};

std::vector<std::byte> random_bytes(std::uint64_t seed, std::size_t n)
{
    xorshift_random rng{seed};
    std::vector<std::byte> v;
    v.reserve(n);
    for (std::size_t i = 0; i < n; ++i)
        v.push_back(static_cast<std::byte>(rng.next() & 0xFFU));
    return v;
}

dictionary_object early_change_params(bool early_change)
{
    dictionary_object params;
    params.set("EarlyChange", object{number_object{std::int64_t{early_change ? 1 : 0}}});
    return params;
}

std::vector<std::byte> pack_bits(const std::vector<int>& codes, int code_size)
{
    std::vector<std::byte> bytes;
    int bit_pos = 0;

    for (int code : codes)
    {
        for (int i = code_size - 1; i >= 0; --i)
        {
            const int byte_idx = bit_pos / 8;
            while (byte_idx >= static_cast<int>(bytes.size()))
                bytes.push_back(std::byte(0));

            const int bit_idx = 7 - (bit_pos % 8);
            if ((code >> i) & 1)
                bytes[static_cast<std::size_t>(byte_idx)] |= std::byte(1 << bit_idx);

            ++bit_pos;
        }
    }

    return bytes;
}

